import { readFileSync, readdirSync } from 'node:fs';
import { postkitBuiltInDefinitions } from '@postkit/core/components';
import { postkitAstroComponents } from './components.js';
import * as bridges from './react-bridges.js';

const componentsDirectory = new URL('../components/', import.meta.url);
const definitions = Object.values(postkitBuiltInDefinitions);
const readme = readFileSync(
  new URL('../../README.md', import.meta.url),
  'utf8',
);
const hydrationSection =
  /^## Hydration policy\n([\s\S]*?)(?=^## )/m.exec(readme)?.[1] ?? '';

function wrapper(name: string): string {
  return readFileSync(new URL(`${name}.astro`, componentsDirectory), 'utf8');
}

describe('generated Astro components', () => {
  it('has one wrapper, bridge and map entry per definition', () => {
    const names = definitions.map(({ name }) => name).sort();
    const wrappers = readdirSync(componentsDirectory)
      .filter((file) => file.endsWith('.astro'))
      .map((file) => file.replace(/\.astro$/, ''))
      .sort();

    expect(wrappers).toEqual(names);
    expect(Object.keys(bridges).sort()).toEqual(names);
    expect(Object.keys(postkitAstroComponents).sort()).toEqual(names);
  });

  it.each(definitions.map((definition) => [definition.name, definition]))(
    '%s declares its hydration policy',
    (name, definition) => {
      const source = wrapper(name);
      const interactive =
        definition.runtime === 'client' || definition.runtime === 'resolver';

      expect(source).toContain(
        'GENERATED by `npm run components:generate`. Do not edit.',
      );
      expect(source).toContain(
        interactive ? 'Hydration: client:visible' : 'Hydration: none',
      );
      expect(source.includes('client:visible')).toBe(interactive);
      expect(source).not.toMatch(/client:(load|idle|only|media)/);
      expect(source.includes('<slot />')).toBe(definition.children === 'mdx');
      if (interactive)
        expect(hydrationSection).toMatch(new RegExp(`\\b${name}\\b`));
    },
  );
});
