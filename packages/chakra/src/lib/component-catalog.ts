import {
  POSTKIT_COMPONENT_MANIFEST_VERSION,
  createPostkitComponentManifest,
  postkitBuiltInDefinitions,
  postkitComponentCategories,
  postkitKitIdForCategory,
  type AnyPostkitComponentDefinition,
  type PostkitComponentCategoryId,
  type PostkitComponentManifestEntry,
  type PostkitComponentRuntime as CorePostkitComponentRuntime,
  type PostkitComponentSupport as CorePostkitComponentSupport,
  type PostkitManifestExample,
  type PostkitManifestPreview,
} from '@postkit/core/components';
import { postkitHeadlessViews } from '@postkit/react';

import { postkitChakraViews } from './chakra-renderer.js';
import {
  POSTKIT_DECLARATION_VERSION,
  type PostkitComponentName,
} from './declarations.js';

/*
 * The component catalog (`component-manifest.json`), manifest v2 (03 §3.2).
 * It's generated by `@postkit/core/components`, the same generator as
 * `createPostkit().manifest()`, from the built-in definitions, with `support`
 * computed from the views `@postkit/react` and `@postkit/chakra` export.
 * `readPostkitComponentManifest` in `@postkit/core/components` still reads v1.
 */

export const POSTKIT_COMPONENT_CATALOG_VERSION =
  POSTKIT_COMPONENT_MANIFEST_VERSION;

export type PostkitComponentCategory =
  (typeof postkitComponentCategories)[PostkitComponentCategoryId];

export type PostkitComponentRuntime = CorePostkitComponentRuntime;

export type PostkitComponentExample = PostkitManifestExample;

export type PostkitComponentPreview = PostkitManifestPreview;

export type PostkitComponentSupport = CorePostkitComponentSupport;

/** A built-in component's v2 manifest entry. */
export interface PostkitComponentCatalogEntry extends PostkitComponentManifestEntry {
  readonly name: PostkitComponentName;
  readonly category: PostkitComponentCategory;
}

export interface PostkitComponentCatalog {
  readonly id: 'postkit.component-catalog';
  readonly version: typeof POSTKIT_COMPONENT_CATALOG_VERSION;
  readonly declarationVersion: number;
  readonly components: Readonly<
    Record<PostkitComponentName, PostkitComponentCatalogEntry>
  >;
}

const builtIns = new Set<AnyPostkitComponentDefinition>(
  Object.values(postkitBuiltInDefinitions),
);

/**
 * Builds a v2 catalog from definitions, keyed and ordered as given. A
 * built-in definition records its kit and `@postkit/core` as its package.
 */
export function createPostkitComponentCatalog(
  definitions: Readonly<Record<string, AnyPostkitComponentDefinition>>,
): PostkitComponentCatalog & {
  readonly declarationVersion: typeof POSTKIT_DECLARATION_VERSION;
} {
  return createPostkitComponentManifest(
    Object.values(definitions).map((definition) =>
      builtIns.has(definition)
        ? {
            definition,
            kit: postkitKitIdForCategory(definition.category),
            package: '@postkit/core',
          }
        : { definition },
    ),
    {
      renderers: {
        headless: Object.keys(postkitHeadlessViews),
        chakra: Object.keys(postkitChakraViews),
      },
    },
  ) as PostkitComponentCatalog & {
    readonly declarationVersion: typeof POSTKIT_DECLARATION_VERSION;
  };
}

export const postkitComponentCatalog: Readonly<{
  id: 'postkit.component-catalog';
  version: typeof POSTKIT_COMPONENT_CATALOG_VERSION;
  declarationVersion: typeof POSTKIT_DECLARATION_VERSION;
  components: Readonly<
    Record<PostkitComponentName, PostkitComponentCatalogEntry>
  >;
}> = createPostkitComponentCatalog(postkitBuiltInDefinitions);
